export const HINDI_RANK_TITLES: { minLevel: number; title: string }[] = [
  { minLevel: 1, title: 'सामान्य ज्ञान प्रशिक्षु' },
  { minLevel: 3, title: 'जीके अन्वेषक' },
  { minLevel: 5, title: 'ज्ञान साधक' },
  { minLevel: 8, title: 'विद्वान' },
  { minLevel: 12, title: 'जीके उस्ताद' },
  { minLevel: 16, title: 'बुद्धिमान महारथी' },
  { minLevel: 20, title: 'ओजी ग्रैंडमास्टर' },
  { minLevel: 25, title: 'जीवंत विश्वकोश' },
];

export function getRankTitleI18n(level: number, lang: Language): string {
  if (lang === 'hi') {
    let title = 'सामान्य ज्ञान प्रशिक्षु';
    for (const item of HINDI_RANK_TITLES) {
      if (level >= item.minLevel) {
        title = item.title;
      }
    }
    return title;
  }
  // English fallback
  const titles = [
    { minLevel: 1, title: 'Trivia Rookie' },
    { minLevel: 3, title: 'GK Explorer' },
    { minLevel: 5, title: 'Knowledge Hunter' },
    { minLevel: 8, title: 'Scholar' },
    { minLevel: 12, title: 'Trivia Maestro' },
    { minLevel: 16, title: 'OG Brainiac' },
    { minLevel: 20, title: 'Grandmaster of GK' },
    { minLevel: 25, title: 'Living Encyclopedia' },
  ];
  let title = 'Trivia Rookie';
  for (const item of titles) {
    if (level >= item.minLevel) {
      title = item.title;
    }
  }
  return title;
}
